import mne
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import matplotlib.pyplot as plt
from sklearn.utils.class_weight import compute_class_weight
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, ConfusionMatrixDisplay
import os
import time
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 加载数据 (真实 20 Subjects) =================
print("Loading 20 Subjects Data...")
subjects = list(range(20))
X_all, y_all = [], []
for sub in subjects:
    try:
        data_path, annot_path = mne.datasets.sleep_physionet.age.fetch_data(subjects=[sub], recording=[1])[0]
        raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
        raw.pick(['EEG Fpz-Cz', 'EOG horizontal', 'EMG submental'])
        raw.filter(l_freq=0.5, h_freq=30.0, verbose=False)
        annot = mne.read_annotations(annot_path)
        for ann in annot:
            if ann['description'] == 'Sleep stage 4': ann['description'] = 'Sleep stage 3'
        raw.set_annotations(annot)
        mapping = {'Sleep stage W': 0, 'Sleep stage 1': 1, 'Sleep stage 2': 2, 'Sleep stage 3': 3, 'Sleep stage R': 4}
        events, _ = mne.events_from_annotations(raw, event_id=mapping)
        epochs = mne.Epochs(raw, events, event_id=mapping, tmin=0, tmax=30.0 - 1/raw.info['sfreq'], baseline=None, preload=True, verbose=False)
        X_all.append(epochs.get_data() * 1e6)
        y_all.append(epochs.events[:, 2])
    except Exception:
        pass

X = np.concatenate(X_all, axis=0)
y = np.concatenate(y_all, axis=0)
X = (X - X.mean(axis=(0, 2), keepdims=True)) / (X.std(axis=(0, 2), keepdims=True) + 1e-8)

# ================= 3. 数据准备 =================
class SleepDataset(Dataset):
    def __init__(self, X, y, seq_length=5):
        self.X, self.y, self.seq_length = X, y, seq_length
    def __len__(self): return len(self.X) - self.seq_length + 1
    def __getitem__(self, idx):
        return torch.tensor(self.X[idx : idx + self.seq_length], dtype=torch.float32), torch.tensor(self.y[idx + self.seq_length - 1], dtype=torch.long)

X_train_val, X_test, y_train_val, y_test = train_test_split(X, y, test_size=0.15, random_state=42, stratify=y)
X_train, X_val, y_train, y_val = train_test_split(X_train_val, y_train_val, test_size=0.176, random_state=42, stratify=y_train_val)

train_loader = DataLoader(SleepDataset(X_train, y_train), batch_size=32, shuffle=True)
val_loader = DataLoader(SleepDataset(X_val, y_val), batch_size=32, shuffle=False)
test_loader = DataLoader(SleepDataset(X_test, y_test), batch_size=32, shuffle=False)

# ================= 4. Plan B 架构 =================
class SingleChannelCNN(nn.Module):
    def __init__(self):
        super(SingleChannelCNN, self).__init__()
        self.conv1 = nn.Conv1d(1, 16, kernel_size=50, stride=6)
        self.bn1 = nn.BatchNorm1d(16)
        self.relu = nn.ReLU()
        self.pool1 = nn.MaxPool1d(4)
        self.conv2 = nn.Conv1d(16, 32, kernel_size=8, stride=2)
        self.bn2 = nn.BatchNorm1d(32)
        self.adaptive_pool = nn.AdaptiveAvgPool1d(1)
    def forward(self, x):
        x = self.pool1(self.relu(self.bn1(self.conv1(x))))
        x = self.relu(self.bn2(self.conv2(x)))
        return self.adaptive_pool(x).squeeze(-1)

class MultiBranchCRNN(nn.Module):
    def __init__(self, n_classes=5):
        super(MultiBranchCRNN, self).__init__()
        self.eeg_cnn = SingleChannelCNN()
        self.eog_cnn = SingleChannelCNN()
        self.emg_cnn = SingleChannelCNN()
        self.lstm = nn.LSTM(input_size=32*3, hidden_size=64, num_layers=1, batch_first=True, bidirectional=True)
        self.dropout = nn.Dropout(0.5)
        self.fc = nn.Linear(128, n_classes)
    def forward(self, x):
        batch_size, seq_length, channels, time_steps = x.size()
        x = x.view(batch_size * seq_length, channels, time_steps)
        f_cat = torch.cat([self.eeg_cnn(x[:, 0:1, :]), self.eog_cnn(x[:, 1:2, :]), self.emg_cnn(x[:, 2:3, :])], dim=1)
        f_seq = f_cat.view(batch_size, seq_length, -1)
        out, _ = self.lstm(f_seq)
        return self.fc(self.dropout(out[:, -1, :]))

model = MultiBranchCRNN()
class_weights = compute_class_weight('balanced', classes=np.unique(y_train), y=y_train)
criterion = nn.CrossEntropyLoss(weight=torch.tensor(class_weights, dtype=torch.float32))
optimizer = optim.Adam(model.parameters(), lr=0.001)

# ================= 5. 完整训练与早停 =================
print("\n开始训练 (30 Epochs 并且带早停)...")
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=2)
best_val_loss = float('inf')
patience_counter = 0
early_stop_patience = 5

for epoch in range(30):
    model.train()
    for inputs, labels in train_loader:
        optimizer.zero_grad()
        loss = criterion(model(inputs), labels)
        loss.backward()
        optimizer.step()

    model.eval()
    running_val_loss = 0.0
    with torch.no_grad():
        for inputs, labels in val_loader:
            running_val_loss += criterion(model(inputs), labels).item()
    avg_val_loss = running_val_loss / len(val_loader)
    scheduler.step(avg_val_loss)

    if avg_val_loss < best_val_loss:
        best_val_loss = avg_val_loss
        patience_counter = 0
        torch.save(model.state_dict(), 'best_real_model.pth')
    else:
        patience_counter += 1
        if patience_counter >= early_stop_patience:
            print(f"早停触发，停止于 Epoch {epoch+1}")
            break

# ================= 6. 原模型真实准确率评估 =================
model.load_state_dict(torch.load('best_real_model.pth'))
model.eval()
all_preds, all_labels = [], []
with torch.no_grad():
    for inputs, labels in test_loader:
        _, predicted = torch.max(model(inputs).data, 1)
        all_preds.extend(predicted.numpy())
        all_labels.extend(labels.numpy())

print("\n================ 原模型评估结果 ================")
print(classification_report(all_labels, all_preds, target_names=['W', 'N1', 'N2', 'N3', 'REM'], zero_division=0))

# ================= 7. 部署与量化校验 =================
print("\n================ 开始边缘量化校验 ================")
# 导出 ONNX 和 量化
dummy_input = torch.randn(1, 5, 3, 3000)
torch.onnx.export(model, dummy_input, "real_sleep.onnx", opset_version=11)
quantized_model = torch.quantization.quantize_dynamic(model, {nn.LSTM, nn.Linear}, dtype=torch.qint8)

# 对比量化后的模型预测结果
quant_preds = []
quantized_model.eval()
with torch.no_grad():
    for inputs, _ in test_loader:
        _, predicted = torch.max(quantized_model(inputs).data, 1)
        quant_preds.extend(predicted.numpy())

print("\n【量化模型】在真实测试集上的评估报告：")
print(classification_report(all_labels, quant_preds, target_names=['W', 'N1', 'N2', 'N3', 'REM'], zero_division=0))

match = np.sum(np.array(all_preds) == np.array(quant_preds))
print(f"✅ 原始模型与量化模型预测结果一致率: {match/len(all_preds)*100:.2f}%")