import mne
import math
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import matplotlib.pyplot as plt
from sklearn.utils.class_weight import compute_class_weight
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, ConfusionMatrixDisplay
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 加载 20 人数据 =================
print("Loading 20 Subjects Data...")
subjects = list(range(20))
X_all, y_all = [], []
for sub in subjects:
    try:
        data_path, annot_path = mne.datasets.sleep_physionet.age.fetch_data(subjects=[sub], recording=[1])[0]
        raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
        raw.pick(['EEG Fpz-Cz', 'EOG horizontal', 'EMG submental'])
        raw.filter(l_freq=0.5, h_freq=30.0, verbose=False)
        annot = mne.read_annotations(annot_path)
        for ann in annot:
            if ann['description'] == 'Sleep stage 4': ann['description'] = 'Sleep stage 3'
        raw.set_annotations(annot)
        mapping = {'Sleep stage W': 0, 'Sleep stage 1': 1, 'Sleep stage 2': 2, 'Sleep stage 3': 3, 'Sleep stage R': 4}
        events, _ = mne.events_from_annotations(raw, event_id=mapping)
        epochs = mne.Epochs(raw, events, event_id=mapping, tmin=0, tmax=30.0 - 1/raw.info['sfreq'], baseline=None, preload=True, verbose=False)
        X_all.append(epochs.get_data() * 1e6)
        y_all.append(epochs.events[:, 2])
    except Exception as e:
        pass

X = np.concatenate(X_all, axis=0)
y = np.concatenate(y_all, axis=0)
X = (X - X.mean(axis=(0, 2), keepdims=True)) / (X.std(axis=(0, 2), keepdims=True) + 1e-8)
print(f"Total samples: {len(X)}")

# ================= 3. 数据加载器 (带轻微噪声) =================
class SleepDataset(Dataset):
    def __init__(self, X, y, seq_length=5, is_train=True):
        self.X = X
        self.y = y
        self.seq_length = seq_length
        self.is_train = is_train
    def __len__(self):
        return len(self.X) - self.seq_length + 1
    def __getitem__(self, idx):
        x_seq = self.X[idx : idx + self.seq_length].copy()
        y_label = self.y[idx + self.seq_length - 1]
        if self.is_train:
            noise = np.random.normal(0, 0.02, x_seq.shape)
            x_seq = x_seq + noise
        return torch.tensor(x_seq, dtype=torch.float32), torch.tensor(y_label, dtype=torch.long)

X_train_val, X_test, y_train_val, y_test = train_test_split(X, y, test_size=0.15, random_state=42, stratify=y)
X_train, X_val, y_train, y_val = train_test_split(X_train_val, y_train_val, test_size=0.176, random_state=42, stratify=y_train_val)

train_loader = DataLoader(SleepDataset(X_train, y_train, is_train=True), batch_size=32, shuffle=True)
val_loader = DataLoader(SleepDataset(X_val, y_val, is_train=False), batch_size=32, shuffle=False)
test_loader = DataLoader(SleepDataset(X_test, y_test, is_train=False), batch_size=32, shuffle=False)

# ================= 4. 定义 Transformer 模型 =================
class PositionalEncoding(nn.Module):
    def __init__(self, d_model, max_len=5):
        super(PositionalEncoding, self).__init__()
        # 创建位置编码矩阵
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model))
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        self.register_buffer('pe', pe)

    def forward(self, x):
        # x shape: (batch, seq_length, d_model)
        return x + self.pe[:x.size(1), :]

class CNNTransformerModel(nn.Module):
    def __init__(self, n_channels=3, n_classes=5, d_model=64):
        super(CNNTransformerModel, self).__init__()
        # 1. 先用 1D CNN 把 3000 个时间点压缩成局部特征
        self.cnn = nn.Sequential(
            nn.Conv1d(n_channels, 16, kernel_size=50, stride=6),
            nn.BatchNorm1d(16),
            nn.ReLU(),
            nn.MaxPool1d(4),
            nn.Conv1d(16, 32, kernel_size=8, stride=2),
            nn.BatchNorm1d(32),
            nn.ReLU(),
            nn.AdaptiveAvgPool1d(1) # 输出形状: (batch*seq, 32, 1)
        )

        # 2. 将 CNN 特征映射到 Transformer 的维度 (64)
        self.fc_proj = nn.Linear(32, d_model)

        # 3. 位置编码与 Transformer 编码器
        self.pos_encoder = PositionalEncoding(d_model)
        encoder_layers = nn.TransformerEncoderLayer(d_model, nhead=4, dim_feedforward=128, dropout=0.1)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layers, num_layers=2)

        # 4. 分类器
        self.fc = nn.Linear(d_model, n_classes)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x):
        # x shape: (batch_size, seq_length, channels, time_steps)
        batch_size, seq_length, channels, time_steps = x.size()
        x = x.view(batch_size * seq_length, channels, time_steps)

        # CNN 提取特征
        cnn_out = self.cnn(x).squeeze(-1) # 形状: (batch*seq, 32)

        # 映射维度，恢复序列
        proj_out = self.fc_proj(cnn_out).view(batch_size, seq_length, -1) # 形状: (batch, seq, 64)

        # 加上位置编码
        pos_out = self.pos_encoder(proj_out)

        # 输入 Transformer (注意：PyTorch默认输入是 seq_len 在前)
        transformer_out = self.transformer_encoder(pos_out.transpose(0, 1))

        # 取最后一个时间步的输出作为预测结果
        final_out = transformer_out[-1, :, :]

        return self.fc(self.dropout(final_out))

model = CNNTransformerModel()
class_weights = compute_class_weight('balanced', classes=np.unique(y_train), y=y_train)
weights_tensor = torch.tensor(class_weights, dtype=torch.float32)
criterion = nn.CrossEntropyLoss(weight=weights_tensor)
optimizer = optim.Adam(model.parameters(), lr=0.0005) # Transformer 通常用较小的学习率

# ================= 5. 训练与早停 =================
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=2)
best_val_loss = float('inf')
patience_counter = 0

print("\nStarting Training with Transformer...")
for epoch in range(30):
    model.train()
    running_loss = 0.0
    for inputs, labels in train_loader:
        optimizer.zero_grad()
        loss = criterion(model(inputs), labels)
        loss.backward()
        optimizer.step()
        running_loss += loss.item()
    avg_train_loss = running_loss / len(train_loader)

    model.eval()
    running_val_loss = 0.0
    with torch.no_grad():
        for inputs, labels in val_loader:
            loss = criterion(model(inputs), labels)
            running_val_loss += loss.item()
    avg_val_loss = running_val_loss / len(val_loader)

    print(f"Epoch {epoch+1}: Train Loss = {avg_train_loss:.4f}, Val Loss = {avg_val_loss:.4f}")
    scheduler.step(avg_val_loss)

    if avg_val_loss < best_val_loss:
        best_val_loss = avg_val_loss
        patience_counter = 0
        torch.save(model.state_dict(), 'best_transformer.pth')
    else:
        patience_counter += 1
        if patience_counter >= 5:
            print(f"\n早停触发！")
            break

# ================= 6. 最终测试 =================
model.load_state_dict(torch.load('best_transformer.pth'))
model.eval()
all_preds, all_labels = [], []
with torch.no_grad():
    for inputs, labels in test_loader:
        _, predicted = torch.max(model(inputs).data, 1)
        all_preds.extend(predicted.numpy())
        all_labels.extend(labels.numpy())

print("\nTest Report (CNN + Transformer):")
print(classification_report(all_labels, all_preds, labels=range(5), target_names=['W', 'N1', 'N2', 'N3', 'REM'], zero_division=0))
ConfusionMatrixDisplay.from_predictions(all_labels, all_preds, display_labels=['W', 'N1', 'N2', 'N3', 'REM'], cmap=plt.cm.Purples)
plt.title("CNN + Transformer Sleep Staging")
plt.show()