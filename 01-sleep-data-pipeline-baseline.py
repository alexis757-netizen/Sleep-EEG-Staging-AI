import mne
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import welch
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import cross_val_predict, StratifiedKFold
from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 数据加载与对齐 =================
print("正在加载数据并对齐标签...")
data_path, annot_path = mne.datasets.sleep_physionet.age.fetch_data(subjects=[0], recording=[1])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
raw.pick(['EEG Fpz-Cz'])
raw.filter(l_freq=0.5, h_freq=30.0, verbose=False)

annot = mne.read_annotations(annot_path)
# 修复深睡 3 和 4 的标签冲突
for ann in annot:
    if ann['description'] == 'Sleep stage 4':
        ann['description'] = 'Sleep stage 3'
raw.set_annotations(annot)

# 映射标签 (1=W清醒, 2=N1浅睡, 3=N2中睡, 4=N3深睡, 5=R做梦)
mapping = {'Sleep stage W': 1, 'Sleep stage 1': 2, 'Sleep stage 2': 3,
           'Sleep stage 3': 4, 'Sleep stage R': 5}
events, _ = mne.events_from_annotations(raw, event_id=mapping)

epochs = mne.Epochs(raw, events, event_id=mapping, tmin=0, tmax=30.0 - 1/raw.info['sfreq'],
                    baseline=None, preload=True, verbose=False)

X_raw = epochs.get_data() * 1e6 # 提取波形数据
y = epochs.events[:, 2]        # 提取标签
fs = raw.info['sfreq']
print(f"✅ 对齐成功，共 {len(epochs)} 个 30 秒片段。")

# ================= 3. 第一战：可视化“经典睡眠波形” =================
print("\n正在绘制不同睡眠阶段的波形图...")
times = np.arange(X_raw.shape[2]) / fs
# 找出各个阶段的样本索引
idx_wake = np.where(y == 1)[0]
idx_n2 = np.where(y == 3)[0]
idx_n3 = np.where(y == 4)[0]

fig, axes = plt.subplots(3, 1, figsize=(12, 8))
# 如果数据里有这个阶段，就画出来
if len(idx_wake) > 0: axes[0].plot(times, X_raw[idx_wake[0]][0], color='blue', linewidth=0.5)
axes[0].set_title("Sleep Stage W (Wake) - High Frequency, Low Amplitude")
if len(idx_n2) > 0: axes[1].plot(times, X_raw[idx_n2[0]][0], color='green', linewidth=0.5)
axes[1].set_title("Sleep Stage N2 - Look for Spindles/K-complexes")
if len(idx_n3) > 0: axes[2].plot(times, X_raw[idx_n3[0]][0], color='red', linewidth=0.5)
axes[2].set_title("Sleep Stage N3 (Deep Sleep) - Huge Delta Waves")
axes[2].set_xlabel("Time (s)")
for ax in axes:
    ax.set_ylabel("Amplitude (uV)")
    ax.grid(True)
plt.tight_layout()
plt.show()

# ================= 4. 第二战：提取特征并分类 =================
print("\n正在提取频段能量特征...")
X_features = []
for i in range(len(X_raw)):
    signal = X_raw[i][0]
    freqs, psd = welch(signal, fs, nperseg=int(fs*2))

    delta_power = np.sum(psd[(freqs >= 0.5) & (freqs < 4)])
    theta_power = np.sum(psd[(freqs >= 4) & (freqs < 8)])
    alpha_power = np.sum(psd[(freqs >= 8) & (freqs < 12)])
    beta_power = np.sum(psd[(freqs >= 12) & (freqs < 30)])

    total_power = delta_power + theta_power + alpha_power + beta_power + 1e-10
    X_features.append([delta_power/total_power, theta_power/total_power,
                       alpha_power/total_power, beta_power/total_power])

X = np.array(X_features)

# 计算各类别的样本数量，决定交叉验证的折数（防止某个类别样本太少报错）
min_class_count = min(np.bincount(y)[1:])
n_splits = min(5, min_class_count) # 如果最少的类只有2个，就分2折
print(f"各类别样本数: {np.bincount(y)[1:]}，将使用 {n_splits} 折交叉验证。")

clf = RandomForestClassifier(n_estimators=100, random_state=42, class_weight='balanced')
cv = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)

print("正在训练多分类模型...")
y_pred = cross_val_predict(clf, X, y, cv=cv)

# 画混淆矩阵
plt.figure(figsize=(8, 6))
cm = confusion_matrix(y, y_pred)
disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=['W', 'N1', 'N2', 'N3', 'REM'])
disp.plot(cmap=plt.cm.Blues)
plt.title(f"Sleep Staging Confusion Matrix ({n_splits}-Fold CV)")
plt.show()