import mne
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import matplotlib.pyplot as plt
from scipy.signal import welch
from sklearn.utils.class_weight import compute_class_weight
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, ConfusionMatrixDisplay
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 加载 20 人数据 =================
print("Loading 20 Subjects Data... (Please wait)")
subjects = list(range(20))
X_all, y_all = [], []

for sub in subjects:
    try:
        data_path, annot_path = mne.datasets.sleep_physionet.age.fetch_data(subjects=[sub], recording=[1])[0]
        raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
        raw.pick(['EEG Fpz-Cz', 'EOG horizontal', 'EMG submental'])
        raw.filter(l_freq=0.5, h_freq=30.0, verbose=False)
        annot = mne.read_annotations(annot_path)
        for ann in annot:
            if ann['description'] == 'Sleep stage 4': ann['description'] = 'Sleep stage 3'
        raw.set_annotations(annot)
        mapping = {'Sleep stage W': 0, 'Sleep stage 1': 1, 'Sleep stage 2': 2, 'Sleep stage 3': 3, 'Sleep stage R': 4}
        events, _ = mne.events_from_annotations(raw, event_id=mapping)
        epochs = mne.Epochs(raw, events, event_id=mapping, tmin=0, tmax=30.0 - 1/raw.info['sfreq'], baseline=None, preload=True, verbose=False)
        X_all.append(epochs.get_data() * 1e6)
        y_all.append(epochs.events[:, 2])
    except Exception as e:
        pass

X = np.concatenate(X_all, axis=0)
y = np.concatenate(y_all, axis=0)
print(f"Total samples: {len(X)}")

# 独立标准化波形
X = (X - X.mean(axis=(0, 2), keepdims=True)) / (X.std(axis=(0, 2), keepdims=True) + 1e-8)

# ================= 3. 提取频域特征 (Welch PSD) =================
print("Extracting Frequency Features (PSD)...")
fs = 100 # Sleep-EDF 采样率通常是 100Hz

def extract_psd_features(epoch_data):
    # 我们只提取 EEG (第0个通道) 的 5 个标准医学频段能量
    eeg_data = epoch_data[0]
    freqs, psd = welch(eeg_data, fs, nperseg=fs*2)

    # 划分频段
    bands = [(0.5, 4), (4, 8), (8, 12), (12, 16), (16, 30)] # Delta, Theta, Alpha, Sigma, Beta
    features = []
    for low, high in bands:
        idx = np.logical_and(freqs >= low, freqs <= high)
        # 计算该频段内的面积（能量总和）
        band_power = np.sum(psd[idx])
        features.append(band_power)

    # 归一化：计算相对能量占比
    total_power = sum(features) + 1e-8
    features = [f / total_power for f in features]
    return features

# 为每个样本提取频域特征
X_freq = np.array([extract_psd_features(sample) for sample in X])
print(f"Frequency Features Shape: {X_freq.shape}") # 应该是 (样本数, 5)

# ================= 4. 自定义 Dataset (双输入) =================
class SleepDualDataset(Dataset):
    def __init__(self, X, X_freq, y, seq_length=5):
        self.X = X
        self.X_freq = X_freq
        self.y = y
        self.seq_length = seq_length
    def __len__(self):
        return len(self.X) - self.seq_length + 1
    def __getitem__(self, idx):
        # 1. 波形序列
        x_seq = self.X[idx : idx + self.seq_length]
        # 2. 频域序列 (取当前时刻的频域特征)
        x_f = self.X_freq[idx + self.seq_length - 1]
        # 3. 标签
        y_label = self.y[idx + self.seq_length - 1]
        return torch.tensor(x_seq, dtype=torch.float32), torch.tensor(x_f, dtype=torch.float32), torch.tensor(y_label, dtype=torch.long)

# 切分数据
X_train_val, X_test, Xf_train_val, Xf_test, y_train_val, y_test = train_test_split(X, X_freq, y, test_size=0.15, random_state=42, stratify=y)
X_train, X_val, Xf_train, Xf_val, y_train, y_val = train_test_split(X_train_val, Xf_train_val, y_train_val, test_size=0.176, random_state=42, stratify=y_train_val)

train_loader = DataLoader(SleepDualDataset(X_train, Xf_train, y_train), batch_size=32, shuffle=True)
val_loader = DataLoader(SleepDualDataset(X_val, Xf_val, y_val), batch_size=32, shuffle=False)
test_loader = DataLoader(SleepDualDataset(X_test, Xf_test, y_test), batch_size=32, shuffle=False)

class_weights = compute_class_weight('balanced', classes=np.unique(y_train), y=y_train)
weights_tensor = torch.tensor(class_weights, dtype=torch.float32)

# ================= 5. 时频双流融合网络 =================
class SingleChannelCNN(nn.Module):
    def __init__(self):
        super(SingleChannelCNN, self).__init__()
        self.conv1 = nn.Conv1d(1, 16, kernel_size=50, stride=6)
        self.bn1 = nn.BatchNorm1d(16)
        self.relu = nn.ReLU()
        self.pool1 = nn.MaxPool1d(4)
        self.conv2 = nn.Conv1d(16, 32, kernel_size=8, stride=2)
        self.bn2 = nn.BatchNorm1d(32)
        self.adaptive_pool = nn.AdaptiveAvgPool1d(1)
    def forward(self, x):
        x = self.pool1(self.relu(self.bn1(self.conv1(x))))
        x = self.relu(self.bn2(self.conv2(x)))
        return self.adaptive_pool(x).squeeze(-1)

class DualStreamCRNN(nn.Module):
    def __init__(self, n_classes=5):
        super(DualStreamCRNN, self).__init__()
        # 分支 1：时间流 (CNN + LSTM)
        self.eeg_cnn = SingleChannelCNN()
        self.eog_cnn = SingleChannelCNN()
        self.emg_cnn = SingleChannelCNN()
        self.lstm = nn.LSTM(input_size=32*3, hidden_size=64, num_layers=1, batch_first=True, bidirectional=True)

        # 分支 2：频率流 (一个小 MLP)
        self.freq_fc = nn.Sequential(
            nn.Linear(5, 16),
            nn.ReLU(),
            nn.Linear(16, 32)
        )

        # 最终融合
        self.dropout = nn.Dropout(0.5)
        self.fc = nn.Linear(128 + 32, n_classes) # LSTM 输出 128，频域输出 32

    def forward(self, x_seq, x_freq):
        # --- 时间流 ---
        batch_size, seq_length, channels, time_steps = x_seq.size()
        x_seq = x_seq.view(batch_size * seq_length, channels, time_steps)
        x_eeg = x_seq[:, 0:1, :]
        x_eog = x_seq[:, 1:2, :]
        x_emg = x_seq[:, 2:3, :]
        f_cat = torch.cat([self.eeg_cnn(x_eeg), self.eog_cnn(x_eog), self.emg_cnn(x_emg)], dim=1)
        f_seq = f_cat.view(batch_size, seq_length, -1)
        out_time, _ = self.lstm(f_seq)
        out_time = out_time[:, -1, :] # (batch, 128)

        # --- 频率流 ---
        out_freq = self.freq_fc(x_freq) # (batch, 32)

        # --- 融合 ---
        out_combined = torch.cat([out_time, out_freq], dim=1) # (batch, 160)
        return self.fc(self.dropout(out_combined))

model = DualStreamCRNN()
criterion = nn.CrossEntropyLoss(weight=weights_tensor)
optimizer = optim.Adam(model.parameters(), lr=0.001)

# ================= 6. 训练与早停 =================
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=2)
best_val_loss = float('inf')
patience_counter = 0
early_stop_patience = 5
train_losses, val_losses = [], []

print("\nStarting Dual-Stream Training (Time + Frequency)...")
for epoch in range(30):
    model.train()
    running_loss = 0.0
    for x_seq, x_freq, labels in train_loader:
        optimizer.zero_grad()
        loss = criterion(model(x_seq, x_freq), labels)
        loss.backward()
        optimizer.step()
        running_loss += loss.item()
    avg_train_loss = running_loss / len(train_loader)
    train_losses.append(avg_train_loss)

    model.eval()
    running_val_loss = 0.0
    with torch.no_grad():
        for x_seq, x_freq, labels in val_loader:
            loss = criterion(model(x_seq, x_freq), labels)
            running_val_loss += loss.item()
    avg_val_loss = running_val_loss / len(val_loader)
    val_losses.append(avg_val_loss)

    print(f"Epoch {epoch+1}: Train Loss = {avg_train_loss:.4f}, Val Loss = {avg_val_loss:.4f}")
    scheduler.step(avg_val_loss)

    if avg_val_loss < best_val_loss:
        best_val_loss = avg_val_loss
        patience_counter = 0
        torch.save(model.state_dict(), 'best_dual_model.pth')
    else:
        patience_counter += 1
        if patience_counter >= early_stop_patience:
            print(f"\n早停触发！在 Epoch {epoch+1} 停止训练。")
            break

# ================= 7. 最终测试 =================
model.load_state_dict(torch.load('best_dual_model.pth'))
model.eval()
all_preds, all_labels = [], []
with torch.no_grad():
    for x_seq, x_freq, labels in test_loader:
        _, predicted = torch.max(model(x_seq, x_freq).data, 1)
        all_preds.extend(predicted.numpy())
        all_labels.extend(labels.numpy())

print("\nTest Report (Dual-Stream: Time + Freq):")
print(classification_report(all_labels, all_preds, labels=range(5), target_names=['W', 'N1', 'N2', 'N3', 'REM'], zero_division=0))
ConfusionMatrixDisplay.from_predictions(all_labels, all_preds, display_labels=['W', 'N1', 'N2', 'N3', 'REM'], cmap=plt.cm.Oranges)
plt.title("Dual-Stream (Time+Freq) Sleep Staging")
plt.show()

plt.figure(figsize=(10, 5))
plt.plot(train_losses, label='Train Loss', color='blue')
plt.plot(val_losses, label='Validation Loss', color='red')
plt.title("Dual-Stream Training Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.show()